static int rf_table[N_UNIT][N_UNIT];
static int rf_init = 0;

int rapidfire(int s, int t) {
    if (!rf_init) {
        for (size_t i = 0; i < sizeof(RFT) / sizeof(RFT[0]); i++) rf_table[RFT[i].s][RFT[i].t] = RFT[i].v;
        rf_init = 1;
    }
    if (s < 0 || t < 0 || s >= N_UNIT || t >= N_UNIT) return 0;
    return rf_table[s][t];
}

int unit_item(int u) { return u < N_SHIP ? T_END + u : S_END + (u - N_SHIP); }
int item_unit(int id) { return IS_SHIP(id) ? SI(id) : (IS_DEF(id) && DI(id) < N_CDEF ? N_SHIP + DI(id) : -1); }
